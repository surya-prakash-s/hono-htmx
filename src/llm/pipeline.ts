function calculateConfidenceScore(validation: any, specCount: number): number {
  let score = 80; // Base score

  // Increase score for valid HTML
  if (validation.valid) {
    score += 15;
  }

  // Decrease score for errors
  score -= validation.errors.length * 5;

  // Decrease score for warnings
  score -= validation.warnings.length * 2;

  // Increase score for more specs used
  score += Math.min(specCount * 2, 10);

  // Clamp between 0 and 100
  return Math.max(0, Math.min(100, score));
}

function escapeHtml(text: string): string {
  const map: Record<string, string> = {
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#039;',
  };
  return text.replace(/[&<>"']/g, (m) => map[m]);
}
